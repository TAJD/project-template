import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';
import mermaid from 'astro-mermaid';

// <!-- TEMPLATE: fill in -->
// `site` + `base` decide where the built site is served from. A project GitHub
// Pages site lives at https://<user>.github.io/<repo>/, so `base` is the repo
// name; a user/org site or a custom domain wants `base: '/'`. Change these four
// values when stamping this template into a real project.
const SITE = 'https://tajd.github.io';
const BASE = '/project-template';
const TITLE = 'project-template';
const DESCRIPTION =
  'A pnpm-workspace starter for a React + Vite frontend and a Hono API on Cloudflare Workers, with deletable feature modules.';
// <!-- /TEMPLATE -->

export default defineConfig({
  site: SITE,
  base: BASE,
  integrations: [
    // Must come before starlight() — it rewrites ```mermaid fences before
    // Starlight's Expressive Code claims them as plain code blocks. autoTheme
    // follows the site's light/dark toggle.
    mermaid({ autoTheme: true }),
    starlight({
      title: TITLE,
      description: DESCRIPTION,
      customCss: ['./src/styles/theme.css'],
      plugins: [
        starlightLinksValidator({
          // Pages link to each other relatively so a `base` change stays a
          // one-file edit (index.mdx). The validator still resolves and checks
          // every one of them; this only lifts its default ban on the style.
          errorOnRelativeLinks: false,
        }),
      ],
      sidebar: [
        {
          // Read order: what it is, run it, stamp it, keep it current.
          label: 'Start here',
          items: [
            { label: 'Overview', link: '/' },
            { label: 'Quickstart', slug: 'start/quickstart' },
            { label: 'New project checklist', slug: 'start/new-project' },
            { label: 'Staying up to date', slug: 'start/updating' },
            { label: 'Developing on Windows', slug: 'start/windows-notes' },
          ],
        },
        // Autogenerated so new pages appear without touching this file
        // (order comes from each page's `sidebar.order` frontmatter).
        { label: 'Modules', items: [{ autogenerate: { directory: 'modules' } }] },
        { label: 'Architecture', items: [{ autogenerate: { directory: 'architecture' } }] },
      ],
    }),
  ],
});
